export function getLessonById(id: string): LessonData | undefined {
  return LESSONS_DATA.find((lesson) => lesson.id === id);
}

export function getLessonsByModule(moduleName: string): LessonData[] {
  return LESSONS_DATA.filter((lesson) => lesson.module === moduleName);
}

export function getModuleNames(): string[] {
  const seen = new Set<string>();
  return LESSONS_DATA.reduce<string[]>((acc, lesson) => {
    if (!seen.has(lesson.module)) {
      seen.add(lesson.module);
      acc.push(lesson.module);
    }
    return acc;
  }, []);
}

export function getNextLesson(currentId: string): LessonData | undefined {
  const index = LESSONS_DATA.findIndex((l) => l.id === currentId);
  if (index === -1 || index === LESSONS_DATA.length - 1) return undefined;
  return LESSONS_DATA[index + 1];
}

export function getPrevLesson(currentId: string): LessonData | undefined {
  const index = LESSONS_DATA.findIndex((l) => l.id === currentId);
  if (index <= 0) return undefined;
  return LESSONS_DATA[index - 1];
}

export function getTotalLessons(): number {
  return LESSONS_DATA.length;
}

export function getModuleProgress(moduleName: string, completedIds: string[]): { done: number; total: number } {
  const moduleLessons = getLessonsByModule(moduleName);
  const done = moduleLessons.filter((l) => completedIds.includes(l.id)).length;
  return { done, total: moduleLessons.length };
}